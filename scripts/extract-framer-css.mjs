#!/usr/bin/env node
/**
 * Extracts CSS rules embedded as template literals inside Framer compiled JS
 * assets and writes them to app/framer-generated.css.
 *
 * Framer injects CSS at runtime via document.styleSheet.insertRule(). To remove
 * the Framer runtime entirely and let Next.js own the page, we extract those rules
 * to a static file that Next.js can serve instead.
 *
 * Run after replacing Framer assets:
 *   node scripts/extract-framer-css.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const assetsDir = new URL("../public/assets/", import.meta.url);
const outputFile = new URL("../app/framer-generated.css", import.meta.url);

const files = await readdir(assetsDir);
const mjsFiles = files.filter((f) => f.endsWith(".mjs"));

const cssRules = new Set();

for (const file of mjsFiles) {
  const content = await readFile(join(assetsDir.pathname, file), "utf8");

  // Match every backtick-delimited string then filter for CSS rules.
  // We skip strings with template expressions (${...}) since they can't be
  // resolved statically. We also require the string to look like a real CSS
  // rule: starts with a CSS selector character and contains "property: value".
  const backtickRe = /`([^`]*)`/g;
  const cssSelectorStart = /^(?:\.framer-|\.svgContainer|\.rich-text|:root|\[data-)/;
  const cssPropertyPair = /[a-z-]+:\s*[^;]+;/; // e.g. "display: flex;"

  for (const [, str] of content.matchAll(backtickRe)) {
    if (str.includes("${")) continue; // skip template expressions

    const trimmed = str.trim();
    if (
      trimmed.length > 15 &&
      trimmed.includes("{") &&
      trimmed.includes("}") &&
      cssSelectorStart.test(trimmed) &&
      cssPropertyPair.test(trimmed)
    ) {
      cssRules.add(trimmed);
    }
  }
}

// A handful of rules from framer.CkI1Tnt1.mjs use dynamic class names (${By},
// ${Vy}) and can't be extracted. Add the known-static ones manually:
cssRules.add(
  ".framer-lightbox-container { opacity: 1 !important; pointer-events: auto !important; }"
);
cssRules.add(".svgContainer svg { display: block; }");

const header = [
  "/*",
  " * framer-generated.css",
  " * Auto-generated by scripts/extract-framer-css.mjs",
  " * DO NOT EDIT — re-run the script after updating Framer assets.",
  " */",
  "",
].join("\n");

const css = header + [...cssRules].sort().join("\n") + "\n";

await writeFile(outputFile.pathname, css);
console.log(
  `✓ Extracted ${cssRules.size} CSS rules → app/framer-generated.css`
);
